import { readFileSync } from 'node:fs';
import { webcrypto } from 'node:crypto';
import { deflateRawSync, inflateRawSync } from 'node:zlib';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const fixture = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const { unzip, zip } = await import(pathToFileURL(process.argv[3]));
const endpoint = new URL(fixture.endpoint);
assert.equal(endpoint.hostname, 'localhost');
const context = new TextEncoder().encode('nfsu2-xyz keyphrase saves v1');
const base = await webcrypto.subtle.importKey('raw', new TextEncoder().encode(fixture.phrase), 'PBKDF2', false, ['deriveBits']);
const bits = new Uint8Array(await webcrypto.subtle.deriveBits({ name:'PBKDF2',hash:'SHA-256',salt:context,iterations:100000 },base,512));
const token = Buffer.from(bits.slice(32)).toString('base64url');
assert.equal(token,fixture.token);
const key = await webcrypto.subtle.importKey('raw',bits.slice(0,32),'AES-GCM',false,['encrypt','decrypt']);
const response = await fetch(endpoint,{ headers:{ authorization:`Bearer ${token}` } });
assert.equal(response.status,200);
const box = new Uint8Array(await response.arrayBuffer());
const packed = await webcrypto.subtle.decrypt({ name:'AES-GCM',iv:box.slice(1,13),additionalData:context },key,box.slice(13));
const entries = await unzip(inflateRawSync(new Uint8Array(packed)));
assert.equal(entries.length,1); assert.equal(entries[0].name,'NFS Underground 2/TEST/TEST');
assert.equal(entries[0].data.length,54966);
const browserZip = zip(entries), nonce = webcrypto.getRandomValues(new Uint8Array(12));
const ciphertext = await webcrypto.subtle.encrypt({ name:'AES-GCM',iv:nonce,additionalData:context },key,deflateRawSync(browserZip));
const browserBox = Buffer.concat([Buffer.from([1]),nonce,Buffer.from(ciphertext)]);
const sent = await fetch(endpoint,{ method:'PUT', headers:{ authorization:`Bearer ${token}`,'if-match':response.headers.get('etag') },body:browserBox });
assert.equal(sent.status,200);
console.log('vault_browser: donor ZIP reader opened native upload; donor ZIP writer + WebCrypto uploaded compatible saves');

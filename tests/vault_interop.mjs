import { readFileSync } from 'node:fs';
import { webcrypto } from 'node:crypto';
import { inflateRawSync } from 'node:zlib';
import assert from 'node:assert/strict';
const fixture = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const decode = text => Buffer.from(text, 'base64');
const context = new TextEncoder().encode('nfsu2-xyz keyphrase saves v1');
const base = await webcrypto.subtle.importKey('raw', new TextEncoder().encode(fixture.phrase), 'PBKDF2', false, ['deriveBits']);
const bits = new Uint8Array(await webcrypto.subtle.deriveBits({ name:'PBKDF2', hash:'SHA-256', salt:context, iterations:100000 }, base, 512));
assert.equal(Buffer.from(bits.slice(32)).toString('base64url'), fixture.token);
assert.deepEqual(Buffer.from(bits.slice(0,32)), decode(fixture.key));
const key = await webcrypto.subtle.importKey('raw', bits.slice(0,32), 'AES-GCM', false, ['encrypt','decrypt']);
const box = decode(fixture.box), plain = decode(fixture.plain);
assert.equal(box[0], 1);
const decrypted = await webcrypto.subtle.decrypt({ name:'AES-GCM',iv:box.subarray(1,13),additionalData:context },key,box.subarray(13));
assert.deepEqual(Buffer.from(decrypted),plain);
const encrypted = await webcrypto.subtle.encrypt({ name:'AES-GCM',iv:box.subarray(1,13),additionalData:context },key,plain);
assert.deepEqual(Buffer.from(encrypted),box.subarray(13));
assert.deepEqual(inflateRawSync(decode(fixture.deflated)),plain);
console.log('vault_interop: browser WebCrypto PBKDF2, token, AES-GCM wire bytes and raw-deflate match Swift');

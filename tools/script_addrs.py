#!/usr/bin/env python3
"""script_addrs.py -- the game addresses the test scripts use, for the runner.

    tools/script_addrs.py [--check]

Scripts (tests/scripts/*.txt, tests/input/*.seq, the LAN race generator
tests/net/gen_lan_race.py) write European SPEED2.EXE addresses, as GA() does
in the runtime.  This writes runtime/autotest_addrs.h: one
"{ 0x...u, GA(0x...u) }," line per address in the executable's range, which
runtime/autotest.c uses to map a script's addresses on the North American
build (tools/addrmap.py header, run by link.sh, maps every GA() literal and
fails on one it cannot map).  --check only says whether the header is up to
date (exit 1 if not).
"""
import os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LO, HI = 0x00401000, 0x00a00000
HEX = re.compile(r'(?<![0-9A-Za-z_])0x([0-9a-fA-F]{6,8})u?(?![0-9A-Za-z_])')
SEQ_PEEK = re.compile(r'(?:^|,)\s*\+?\d+:peek:([0-9a-fA-F]{6,8})\b')


def addrs():
    found = set()
    files = sorted(glob.glob(os.path.join(ROOT, 'tests/scripts/*.txt')) +
                   glob.glob(os.path.join(ROOT, 'tests/input/*.seq')) +
                   glob.glob(os.path.join(ROOT, 'tests/net/gen_lan_race.py')))
    for f in files:
        for line in open(f, encoding='utf-8', errors='replace'):
            code = line.split('#', 1)[0] if not f.endswith('.py') else line
            for m in HEX.finditer(code):
                v = int(m.group(1), 16)
                if LO <= v < HI: found.add(v)
            if f.endswith('.seq'):
                for m in SEQ_PEEK.finditer(code.strip()):
                    v = int(m.group(1), 16)
                    if LO <= v < HI: found.add(v)
    found.add(0x008654a4)                      # GameFlowManager: always there
    return sorted(found)


def render(vals):
    out = ['/* Generated by tools/script_addrs.py -- do not edit.',
           ' * Every game address the test scripts use (European), and the same',
           ' * address on this build: runtime/autotest.c maps a script\'s numbers',
           ' * through it. */']
    out += ['{ 0x%08xu, GA(0x%08xu) },' % (v, v) for v in vals]
    return '\n'.join(out) + '\n'


def main():
    path = os.path.join(ROOT, 'runtime/autotest_addrs.h')
    text = render(addrs())
    old = open(path).read() if os.path.exists(path) else ''
    if '--check' in sys.argv[1:]:
        if old != text:
            print('runtime/autotest_addrs.h is out of date: run tools/script_addrs.py'); return 1
        return 0
    if old != text:
        open(path, 'w').write(text)
    print('runtime/autotest_addrs.h: %d addresses' % (text.count('GA(')))
    return 0


if __name__ == '__main__':
    sys.exit(main())

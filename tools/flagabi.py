#!/usr/bin/env python3
"""Inter-function flag liveness (ABI): are flags really live at call and return
points?

Code generated by MSVC doesn't read a flag returned from a call, and the callee
doesn't read the caller's flags on entry.  The lifter, however, treats all flags
as live at call and ret (conservative): the six flags of the last flag-producing
instruction before a call are always computed and written to memory.  This tool
PROVES the assumption:

  entry_live[f]  : flags read at f's entry (before being defined)
  flag_returning : targets of direct calls whose flags are read after the call
  indirect_reader: call sites whose flags are read after an indirect call

Fixed point: call T -> def F_ALL, use entry_live[T] (indirect: F_ALL);
ret -> live 0, F_ALL if f is flag_returning.

    ./.venv/bin/python tools/flagabi.py <SPEED2.EXE> [output.json]

output.json is passed to genall.py with FLAGABI=<json> (see lift.flag_liveness).
"""
import sys, os, json, collections, time, multiprocessing as mp
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lift import Lifter, abi_cfg, abi_liveness, F_ALL
from capstone.x86 import X86_OP_IMM

EXE = sys.argv[1]
_L = None

def _init():
    global _L
    _L = Lifter(EXE, comments=False)

def summarize(a):
    try:
        blocks, calls = _L.discover(a)
    except Exception:
        return a, None
    return a, abi_cfg(blocks, _L.in_text)


def analyze(G):
    """fixed point -> (entry, returning, indirect)"""
    entry = {a: 0 for a in G}
    returning = set()
    for round_no in range(16):
        changed = False
        new = set(); indirect = []
        for a, g in G.items():
            ent, _, after = abi_liveness(g, a, entry, a in returning)
            if ent != entry[a]:
                entry[a] = ent; changed = True
            for adr, (cur, kind, target) in after.items():
                if cur:
                    if kind == 1: new.add(target)
                    else: indirect.append((a, adr, cur))
        if new - returning:
            returning |= new; changed = True
        print(f'  round {round_no}: entry live {sum(1 for v in entry.values() if v)}, '
              f'flag returning {len(returning)}, read after indirect call {len(indirect)}')
        if not changed: break
    return entry, returning, indirect


if __name__ == '__main__':
    out_path = sys.argv[2] if len(sys.argv) > 2 else 'out/flagabi.json'
    t0 = time.time()
    sys.argv = sys.argv[:2]            # genall expects argv[2]=NSHARD
    import genall                      # discover_all: genall.EXE = sys.argv[1]
    funcs = genall.discover_all()
    print(f'{len(funcs)} functions ({time.time()-t0:.0f}s)')
    with mp.Pool(mp.cpu_count(), initializer=_init) as pool:
        G = dict(pool.map(summarize, funcs, chunksize=64))
    G = {a: g for a, g in G.items() if g}
    print(f'summary: {len(G)} functions ({time.time()-t0:.0f}s)')
    entry, returning, indirect = analyze(G)
    json.dump({'entry': {hex(a): v for a, v in entry.items() if v}, 'returning': sorted(hex(a) for a in returning),
               'indirect': [[hex(a), hex(adr), cur] for a, adr, cur in indirect]}, open(out_path, 'w'), indent=0)
    print(f'written: {out_path}  ({time.time()-t0:.0f}s)')
    for a, adr, cur in indirect[:20]:
        print(f'  reads flags after an indirect call: function {a:#x} call {adr:#x} mask {cur:#x}')
    for a in sorted(returning)[:30]:
        print(f'  flag returning: {a:#x}')
    for a, v in sorted(entry.items())[:0]: pass
    print('entry live:', ' '.join(f'{a:#x}:{v:#x}' for a, v in sorted(entry.items()) if v)[:2000])
